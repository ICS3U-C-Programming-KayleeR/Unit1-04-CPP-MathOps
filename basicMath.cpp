#include <iostream>
#include <cmath>

int main() {
    std::cout << "5+7 = " << 5+7 << "\n";  // addition
    std::cout << "56-32 = " << 56-32 << "\n";  // subtraction
    std::cout << "4*31 = " << 4*31 << "\n";  // multiplication
    std::cout << "567.0/9 = " << 567.0/9 << "\n";  // integer division
    std::cout << "128%7 = " << 128%7 << "\n";  // decimal division
    std::cout << "67^2 = " << pow(67, 2) << "\n";  // exponents
    std::cout << "√76 = " << sqrt(76) << "\n";  // square root
}

